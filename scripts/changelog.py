#!/usr/bin/env python3
"""Regenerate the per-release list at the bottom of CHANGELOG.md from GitHub releases (needs `gh`).

The hand-written part above the marker stays as it is. Usage: python3 scripts/changelog.py [--check]
"""
import json
import re
import subprocess
import sys
from pathlib import Path

MARK = '<!-- releases: generated by scripts/changelog.py, do not edit below -->'
FILE = Path(__file__).resolve().parents[1] / 'CHANGELOG.md'


def gh(*args):
    return json.loads(subprocess.check_output(['gh', *args]))


def section(tag, date, body):
    items = re.findall(r'^\* (.+?) by @\S+ in https://github.com/[^/]+/[^/]+/pull/(\d+)', body, re.M)
    lines = [f'### {tag} · {date}'] + [f'- {title} (#{num})' for title, num in items]
    return '\n'.join(lines if items else lines + ['- (no pull requests listed)'])


def generate():
    releases = sorted(gh('release', 'list', '--limit', '200', '--json', 'tagName,publishedAt'),
                      key=lambda r: r['publishedAt'], reverse=True)
    parts = [section(r['tagName'], r['publishedAt'][:10], gh('release', 'view', r['tagName'], '--json', 'body')['body'])
             for r in releases]
    return '\n\n'.join(parts) + '\n'


def selftest():
    body = '## What\'s Changed\n* feat(a): one by @u in https://github.com/o/r/pull/7\n* fix(b): two by @u in https://github.com/o/r/pull/9\n'
    assert section('v1.0.0', '2026-01-02', body) == '### v1.0.0 · 2026-01-02\n- feat(a): one (#7)\n- fix(b): two (#9)'
    assert section('v1.0.1', '2026-01-03', 'nothing').endswith('(no pull requests listed)')


if __name__ == '__main__':
    selftest()
    text = FILE.read_text()
    assert MARK in text, 'marker missing in CHANGELOG.md'
    new = text.split(MARK)[0] + MARK + '\n\n' + generate()
    if '--check' in sys.argv:
        sys.exit(0 if new == text else 'CHANGELOG.md is out of date: run python3 scripts/changelog.py')
    FILE.write_text(new)
